import { strict as assert } from 'node:assert';
import { describe, it } from 'node:test';

import { runWritingAiScan } from '../index.js';

const TEXT = 'The server starts. The worker drains the queue. The cache clears old entries. The log rotates. The monitor alerts.';

function response(payload, { ok = true, status = 200 } = {}) {
  return {
    ok,
    status,
    async text() {
      return JSON.stringify(payload);
    },
  };
}

function components({ aigc = 0.9, jev = 0.8, slow = null } = {}) {
  return async (url) => {
    if (url === 'http://aigc') return response({ aiProbability: aigc });
    if (url === 'https://api.typesafe.ai/v1/systemone') {
      return response({
        model: 'jev-test',
        answers: { authorship: { type: 'choice', choice: jev >= 0.5 ? 'ai' : 'human', probabilities: { human: 1 - jev, ai: jev } } },
      });
    }
    if (url === 'http://slow') return response({ label: slow });
    throw new Error(`unexpected URL ${url}`);
  };
}

const ensembleEnv = {
  AIGC_DETECTOR_URL: 'http://aigc',
  TYPESAFE_API_KEY: 'key',
};

describe('writing_ai_scan ensemble integration', () => {
  it('combines AIGC and Jev with the reviewed weights', async () => {
    const output = await runWritingAiScan(
      { text: TEXT, language: 'en', detector: 'ensemble', allowNetwork: true, mode: 'standard' },
      process.cwd(),
      { env: ensembleEnv, fetchImpl: components() },
    );

    assert.equal(output.ok, true);
    assert.equal(output.details.detector, 'ensemble');
    assert.equal(output.details.ensemble.components.aigc, 0.9);
    assert.equal(output.details.ensemble.components.jev, 0.8);
    assert.equal(output.details.ensemble.score, 0.8325);
    assert.equal(output.details.ensemble.label, 'ai');
    assert.equal(output.details.ensemble.source, 'weighted');
    assert.equal(output.details.ensemble.jevModel, 'jev-test');
    assert.equal(output.details.ensemble.jevPrompt.name, 'authorship');
    assert.match(output.details.ensemble.jevPrompt.instructions, /human or generated by an AI/u);
    assert.match(output.report, /AIGC \+ Jev Ensemble Decision/u);
    assert.match(output.report, /AIGC P\(AI\) = 0\.900/u);
    assert.match(output.report, /Jev P\(AI\) = 0\.800/u);
  });

  it('uses the ensemble in auto mode when both components are configured', async () => {
    const output = await runWritingAiScan(
      { text: TEXT, language: 'en', detector: 'auto', allowNetwork: true },
      process.cwd(),
      { env: ensembleEnv, fetchImpl: components() },
    );
    assert.equal(output.ok, true);
    assert.equal(output.details.detector, 'ensemble');
    assert.equal(output.details.ensemble.label, 'ai');
  });

  it('uses the OMP judge model when TYPESAFE_API_KEY is absent', async () => {
    const output = await runWritingAiScan(
      { text: TEXT, language: 'en', detector: 'ensemble', allowNetwork: true, mode: 'standard' },
      process.cwd(),
      {
        env: { AIGC_DETECTOR_URL: 'http://aigc' },
        judge: async () => ({
          ok: true,
          model: {
            id: 'jev-1.13-free',
            provider: 'opencode-zen',
            baseUrl: 'https://judge.example/zen',
            headers: { authorization: 'Bearer omp' },
          },
        }),
        fetchImpl: async (url, init) => {
          if (url === 'http://aigc') return response({ aiProbability: 0.9 });
          if (url === 'https://judge.example/zen/v1/systemone') {
            assert.equal(init.headers.authorization, 'Bearer omp');
            return response({
              model: 'jev-1.13-free',
              answers: { authorship: { type: 'choice', choice: 'ai', probabilities: { human: 0.2, ai: 0.8 } } },
            });
          }
          throw new Error(`unexpected URL ${url}`);
        },
      },
    );

    assert.equal(output.ok, true);
    assert.equal(output.details.detector, 'ensemble');
    assert.equal(output.details.ensemble.score, 0.8325);
    assert.equal(output.details.ensemble.jevSource, 'omp-judge');
    assert.equal(output.details.ensemble.jevProvider, 'opencode-zen');
    assert.equal(output.details.ensemble.jevModel, 'jev-1.13-free');
    assert.match(output.report, /Jev model = jev-1.13-free/u);
  });

  it('records why the judge fallback was unavailable', async () => {
    const output = await runWritingAiScan(
      { text: TEXT, language: 'en', detector: 'auto', allowNetwork: true },
      process.cwd(),
      { env: { AIGC_DETECTOR_URL: 'http://aigc' }, judge: async () => ({ ok: false, reason: 'no_judge_model' }) },
    );
    assert.equal(output.ok, true);
    assert.equal(output.details.detector, 'local');
    assert.deepEqual(output.details.ensemble.missing, ['TYPESAFE_API_KEY']);
    assert.equal(output.details.ensemble.judgeReason, 'no_judge_model');
  });

  it('records a judge resolver exception without failing the local scan', async () => {
    const output = await runWritingAiScan(
      { text: TEXT, language: 'en', detector: 'auto', allowNetwork: true },
      process.cwd(),
      {
        env: { AIGC_DETECTOR_URL: 'http://aigc' },
        judge: async () => {
          throw new Error('registry unavailable');
        },
      },
    );
    assert.equal(output.ok, true);
    assert.equal(output.details.detector, 'local');
    assert.equal(output.details.ensemble.judgeReason, 'registry unavailable');
  });


  it('defaults a reasonless judge failure to no_judge_model', async () => {
    const output = await runWritingAiScan(
      { text: TEXT, language: 'en', detector: 'auto', allowNetwork: true },
      process.cwd(),
      { env: { AIGC_DETECTOR_URL: 'http://aigc' }, judge: async () => ({ ok: false }) },
    );
    assert.equal(output.details.detector, 'local');
    assert.equal(output.details.ensemble.judgeReason, 'no_judge_model');
  });

  it('records a non-Error judge rejection as text', async () => {
    const output = await runWritingAiScan(
      { text: TEXT, language: 'en', detector: 'auto', allowNetwork: true },
      process.cwd(),
      {
        env: { AIGC_DETECTOR_URL: 'http://aigc' },
        judge: async () => {
          throw 'judge offline';
        },
      },
    );
    assert.equal(output.details.detector, 'local');
    assert.equal(output.details.ensemble.judgeReason, 'judge offline');
  });

  it('uses the slow fallback only inside the uncertainty band', async () => {
    const output = await runWritingAiScan(
      { text: TEXT, language: 'en', detector: 'ensemble', allowNetwork: true },
      process.cwd(),
      {
        env: { ...ensembleEnv, SLOW_DETECTOR_URL: 'http://slow' },
        fetchImpl: components({ aigc: 0.38, jev: 0.38, slow: 'human' }),
      },
    );

    assert.equal(output.ok, true);
    assert.equal(output.details.ensemble.source, 'slow');
    assert.equal(output.details.ensemble.label, 'human');
    assert.equal(output.details.ensemble.components.slow, 'human');
    assert.match(output.report, /Slow fallback = human/u);
  });

  it('keeps the weighted decision when the slow fallback fails', async () => {
    const output = await runWritingAiScan(
      { text: TEXT, language: 'en', detector: 'ensemble', allowNetwork: true },
      process.cwd(),
      {
        env: { ...ensembleEnv, SLOW_DETECTOR_URL: 'http://slow' },
        fetchImpl: async (url) => {
          if (url === 'http://aigc') return response({ aiProbability: 0.38 });
          if (url === 'https://api.typesafe.ai/v1/systemone') {
            return response({ answers: { authorship: { type: 'choice', choice: 'ai', probabilities: { human: 0.62, ai: 0.38 } } } });
          }
          if (url === 'http://slow') return response({ error: 'down' }, { ok: false, status: 500 });
          throw new Error(`unexpected URL ${url}`);
        },
      },
    );

    assert.equal(output.ok, true);
    assert.equal(output.details.ensemble.source, 'weighted');
    assert.equal(output.details.ensemble.uncertain, true);
    assert.match(output.details.ensemble.slowError, /HTTP 500/u);
    assert.match(output.report, /Slow fallback error =/u);
  });

  it('does not call a slow component when none is configured', async () => {
    const output = await runWritingAiScan(
      { text: TEXT, language: 'en', detector: 'ensemble', allowNetwork: true },
      process.cwd(),
      { env: ensembleEnv, fetchImpl: components({ aigc: 0.38, jev: 0.38 }) },
    );

    assert.equal(output.ok, true);
    assert.equal(output.details.ensemble.source, 'weighted');
    assert.equal(output.details.ensemble.components.slow, null);
    assert.equal(output.details.ensemble.slowError, null);
  });

  it('falls back to local scanning in auto mode when the ensemble is not configured', async () => {
    const output = await runWritingAiScan(
      { text: TEXT, language: 'en', detector: 'auto', allowNetwork: true },
      process.cwd(),
      { env: {} },
    );

    assert.equal(output.ok, true);
    assert.equal(output.details.detector, 'local');
    assert.deepEqual(output.details.ensemble.missing, ['AIGC_DETECTOR_URL', 'TYPESAFE_API_KEY']);
    assert.match(output.report, /ensemble not configured/u);
  });

  it('fails closed when ensemble mode is requested without configuration', async () => {
    const output = await runWritingAiScan(
      { text: TEXT, language: 'en', detector: 'ensemble', allowNetwork: true },
      process.cwd(),
      { env: {} },
    );

    assert.equal(output.ok, false);
    assert.match(output.report, /Missing configuration/u);
    assert.match(output.report, /AIGC_DETECTOR_URL/u);
  });

  it('surfaces AIGC and Jev request failures instead of silently using local scoring', async () => {
    const aigcFailure = await runWritingAiScan(
      { text: TEXT, language: 'en', detector: 'ensemble', allowNetwork: true },
      process.cwd(),
      {
        env: ensembleEnv,
        fetchImpl: async (url) => {
          if (url === 'http://aigc') return response({ error: 'down' }, { ok: false, status: 502 });
          return components()(url);
        },
      },
    );
    assert.equal(aigcFailure.ok, false);
    assert.match(aigcFailure.report, /AIGC detector HTTP 502/u);

    const jevFailure = await runWritingAiScan(
      { text: TEXT, language: 'en', detector: 'ensemble', allowNetwork: true },
      process.cwd(),
      {
        env: ensembleEnv,
        fetchImpl: async (url) => {
          if (url === 'http://aigc') return response({ aiProbability: 0.9 });
          return response({ error: 'bad key' }, { ok: false, status: 401 });
        },
      },
    );
    assert.equal(jevFailure.ok, false);
    assert.match(jevFailure.report, /Jev detector HTTP 401/u);
  });


  it('defaults to auto and uses the process environment when options are omitted', async () => {
    const savedAigc = process.env.AIGC_DETECTOR_URL;
    const savedKey = process.env.TYPESAFE_API_KEY;
    delete process.env.AIGC_DETECTOR_URL;
    delete process.env.TYPESAFE_API_KEY;
    try {
      const output = await runWritingAiScan({ text: TEXT, language: 'en', allowNetwork: true }, process.cwd());
      assert.equal(output.ok, true);
      assert.equal(output.details.detector, 'local');
      assert.deepEqual(output.details.ensemble.missing, ['AIGC_DETECTOR_URL', 'TYPESAFE_API_KEY']);
    } finally {
      if (savedAigc === undefined) delete process.env.AIGC_DETECTOR_URL; else process.env.AIGC_DETECTOR_URL = savedAigc;
      if (savedKey === undefined) delete process.env.TYPESAFE_API_KEY; else process.env.TYPESAFE_API_KEY = savedKey;
    }
  });

  it('uses the global fetch when no fetch implementation is injected', async () => {
    const savedFetch = globalThis.fetch;
    globalThis.fetch = components();
    try {
      const output = await runWritingAiScan(
        { text: TEXT, language: 'en', detector: 'ensemble', allowNetwork: true },
        process.cwd(),
        { env: ensembleEnv },
      );
      assert.equal(output.ok, true);
      assert.equal(output.details.ensemble.label, 'ai');
    } finally {
      globalThis.fetch = savedFetch;
    }
  });

  it('reports Chinese ensemble failures in Chinese', async () => {
    const chineseText = '系统开始运行。系统继续运行。系统结束运行。系统保持运行。系统停止运行。';
    const missing = await runWritingAiScan(
      { text: chineseText, language: 'zh', detector: 'ensemble', allowNetwork: true },
      process.cwd(),
      { env: {} },
    );
    assert.match(missing.report, /AIGC \+ Jev 组合检测失败/u);
    assert.match(missing.report, /设置这些环境变量后重试/u);

    const aigcFailure = await runWritingAiScan(
      { text: chineseText, language: 'zh', detector: 'ensemble', allowNetwork: true },
      process.cwd(),
      {
        env: ensembleEnv,
        fetchImpl: async () => response({ error: 'down' }, { ok: false, status: 503 }),
      },
    );
    assert.match(aigcFailure.report, /检查 AIGC_DETECTOR_URL 指向的服务/u);

    const jevFailure = await runWritingAiScan(
      { text: chineseText, language: 'zh', detector: 'ensemble', allowNetwork: true },
      process.cwd(),
      {
        env: ensembleEnv,
        fetchImpl: async (url) => {
          if (url === 'http://aigc') return response({ aiProbability: 0.9 });
          return response({ error: 'bad key' }, { ok: false, status: 401 });
        },
      },
    );
    assert.match(jevFailure.report, /检查 TYPESAFE_API_KEY/u);
  });

  it('requires explicit network opt-in before calling either detector', async () => {
    const auto = await runWritingAiScan(
      { text: TEXT, language: 'en', detector: 'auto' },
      process.cwd(),
      { env: ensembleEnv, fetchImpl: components() },
    );
    assert.equal(auto.ok, true);
    assert.equal(auto.details.detector, 'local');
    assert.equal(auto.details.ensemble.reason, 'network_not_allowed');
    assert.match(auto.report, /Network access was not allowed/u);

    const ensemble = await runWritingAiScan(
      { text: TEXT, language: 'en', detector: 'ensemble' },
      process.cwd(),
      { env: ensembleEnv, fetchImpl: components() },
    );
    assert.equal(ensemble.ok, false);
    assert.match(ensemble.report, /allowNetwork must be true/u);

    const chinese = await runWritingAiScan(
      { text: '系统开始运行。系统继续运行。系统结束运行。系统保持运行。系统停止运行。', language: 'zh', detector: 'ensemble' },
      process.cwd(),
      { env: ensembleEnv, fetchImpl: components() },
    );
    assert.equal(chinese.ok, false);
    assert.match(chinese.report, /网络访问未授权/u);
  });

  it('runs only the local scanner when detector=local', async () => {
    let calls = 0;
    const output = await runWritingAiScan(
      { text: TEXT, language: 'en', detector: 'local' },
      process.cwd(),
      {
        env: ensembleEnv,
        fetchImpl: async () => {
          calls += 1;
          return response({});
        },
      },
    );

    assert.equal(output.ok, true);
    assert.equal(output.details.detector, 'local');
    assert.equal(calls, 0);
  });
});
