const DEFAULT_TYPESAFE_BASE_URL = 'https://api.typesafe.ai';
const DEFAULT_TYPESAFE_MODEL = 'jev-latest';
export const JEV_AUTHORSHIP_PROMPT = Object.freeze({
  name: 'authorship',
  instructions: 'Decide whether the text was written by a human or generated by an AI. Judge the writing itself, not the topic.',
  criteria: Object.freeze({
    human: 'The text reads as human-written prose.',
    ai: 'The text has the statistical or structural signature of AI-generated prose.',
  }),
});

function envValue(env, key) {
  const value = env?.[key];
  return typeof value === 'string' ? value.trim() : '';
}

function authHeaders(token) {
  return token ? { authorization: `Bearer ${token}` } : {};
}

async function postJson(fetchImpl, url, headers, body, label) {
  let response;
  try {
    response = await fetchImpl(url, {
      method: 'POST',
      headers: {
        accept: 'application/json',
        'content-type': 'application/json',
        ...headers,
      },
      body: JSON.stringify(body),
    });
  } catch (error) {
    throw new Error(`${label} request failed: ${error?.message ?? error}`);
  }
  const text = await response.text();
  let data;
  try {
    data = text ? JSON.parse(text) : {};
  } catch {
    throw new Error(`${label} returned non-JSON content`);
  }
  if (!response.ok) {
    throw new Error(`${label} HTTP ${response.status}: ${text.slice(0, 200)}`);
  }
  return data;
}

function probabilityFrom(data) {
  const value = data?.aiProbability ?? data?.probability ?? data?.score;
  if (typeof value !== 'number' || !Number.isFinite(value) || value < 0 || value > 1) {
    return null;
  }
  return value;
}

export async function fetchAigcProbability({ text, language, env = process.env, fetchImpl = fetch }) {
  const url = envValue(env, 'AIGC_DETECTOR_URL');
  if (!url) {
    return { ok: false, code: 'aigc_not_configured', error: 'AIGC_DETECTOR_URL is not set' };
  }
  const token = envValue(env, 'AIGC_DETECTOR_TOKEN');
  try {
    const data = await postJson(
      fetchImpl,
      url,
      authHeaders(token),
      { text, language },
      'AIGC detector',
    );
    const probability = probabilityFrom(data);
    if (probability === null) {
      return { ok: false, code: 'aigc_invalid_response', error: 'AIGC detector response has no aiProbability in [0, 1]' };
    }
    return { ok: true, probability };
  } catch (error) {
    return { ok: false, code: 'aigc_request_failed', error: error.message };
  }
}

export async function fetchJevProbability({ text, env = process.env, fetchImpl = fetch, judgeModel = null }) {
  const token = envValue(env, 'TYPESAFE_API_KEY');
  if (!token && !judgeModel) {
    return {
      ok: false,
      code: 'jev_not_configured',
      error: 'TYPESAFE_API_KEY is not set and no OMP judge model is available',
    };
  }
  const baseUrl = (token
    ? (envValue(env, 'TYPESAFE_BASE_URL') || DEFAULT_TYPESAFE_BASE_URL)
    : String(judgeModel.baseUrl ?? '')).replace(/\/+$/u, '');
  const model = token
    ? (envValue(env, 'TYPESAFE_MODEL') || DEFAULT_TYPESAFE_MODEL)
    : judgeModel.id;
  const headers = token ? authHeaders(token) : { ...judgeModel.headers };
  if (!baseUrl || !model) {
    return { ok: false, code: 'jev_not_configured', error: 'The Jev model has no base URL or model id' };
  }
  const payload = {
    model,
    state: text,
    questions: {
      [JEV_AUTHORSHIP_PROMPT.name]: {
        type: 'choice',
        instructions: JEV_AUTHORSHIP_PROMPT.instructions,
        criteria: { ...JEV_AUTHORSHIP_PROMPT.criteria },
      },
    },
  };
  try {
    const data = await postJson(
      fetchImpl,
      `${baseUrl}/v1/systemone`,
      headers,
      payload,
      'Jev detector',
    );
    const answer = data?.answers?.authorship;
    const source = token ? 'typesafe' : 'omp-judge';
    const probability = answer?.probabilities?.ai;
    if (typeof probability === 'number' && Number.isFinite(probability)) {
      return { ok: true, probability, confidence: answer.confidence, model: data.model ?? model, source };
    }
    if (answer?.choice === 'ai' || answer?.choice === 'human') {
      return {
        ok: true,
        probability: answer.choice === 'ai' ? 1 : 0,
        confidence: answer.confidence,
        model: data.model ?? model,
        source,
      };
    }
    return { ok: false, code: 'jev_invalid_response', error: 'Jev response has no authorship probability or choice' };
  } catch (error) {
    return { ok: false, code: 'jev_request_failed', error: error.message };
  }
}

export async function fetchSlowLabel({ text, language, env = process.env, fetchImpl = fetch }) {
  const url = envValue(env, 'SLOW_DETECTOR_URL');
  if (!url) {
    return { ok: false, code: 'slow_not_configured', error: 'SLOW_DETECTOR_URL is not set' };
  }
  const token = envValue(env, 'SLOW_DETECTOR_TOKEN');
  try {
    const data = await postJson(
      fetchImpl,
      url,
      authHeaders(token),
      { text, language },
      'Slow detector',
    );
    const label = data?.label ?? data?.prediction;
    if (label !== 'ai' && label !== 'human') {
      return { ok: false, code: 'slow_invalid_response', error: 'Slow detector response has no human/ai label' };
    }
    return { ok: true, label };
  } catch (error) {
    return { ok: false, code: 'slow_request_failed', error: error.message };
  }
}

export function ensembleConfiguration(env = process.env, { judgeAvailable = false } = {}) {
  const missing = [];
  if (!envValue(env, 'AIGC_DETECTOR_URL')) missing.push('AIGC_DETECTOR_URL');
  const hasTypesafeKey = Boolean(envValue(env, 'TYPESAFE_API_KEY'));
  if (!hasTypesafeKey && !judgeAvailable) missing.push('TYPESAFE_API_KEY');
  return {
    ready: missing.length === 0,
    missing,
    jevSource: hasTypesafeKey ? 'typesafe' : judgeAvailable ? 'omp-judge' : null,
  };
}
